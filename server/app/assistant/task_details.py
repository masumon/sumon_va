"""Progress / blocker / evidence for a task (manual_sql/0003). Same pattern as identity.py: the columns are reached through a Core
table reference, NOT the ORM model, and every probe runs in a SAVEPOINT, so the app works before and after the owner runs the SQL.

Only the OWNER writes progress and completion (the route is owner-authenticated). Nothing here is ever generated by an AI.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

import sqlalchemy as sa
from sqlalchemy import select, update
from sqlalchemy.ext.asyncio import AsyncSession

STATUSES = ("proposed", "not_started", "in_progress", "blocked", "delayed", "completed", "cancelled")
_T = sa.table("wa_tasks", sa.column("id", sa.Uuid), sa.column("status", sa.String), sa.column("progress", sa.Text), sa.column("blocker", sa.Text),
              sa.column("source_msg_id", sa.Uuid), sa.column("confidence", sa.String), sa.column("assigner_contact_id", sa.Uuid),
              sa.column("updated_at", sa.DateTime(timezone=True)))
FIELDS = ("status", "progress", "blocker", "source_msg_id", "confidence", "assigner_contact_id")


async def ready(db: AsyncSession) -> bool:
    try:
        async with db.begin_nested():
            await db.execute(select(_T.c.status).limit(1))
        return True
    except Exception:  # noqa: BLE001 - manual_sql/0003 has not been run yet
        return False


async def set_details(db: AsyncSession, task_id: Any, **fields: Any) -> bool:
    """Write the given detail fields (only known ones). False, and nothing written, while the SQL is missing."""
    values = {k: v for k, v in fields.items() if k in FIELDS and v is not None}
    if "status" in values and values["status"] not in STATUSES:
        raise ValueError("unknown status")
    if not values or not await ready(db):
        return False
    values["updated_at"] = datetime.now(timezone.utc)
    await db.execute(update(_T).where(_T.c.id == task_id).values(**values))
    return True


async def get_details(db: AsyncSession, task_ids: list[Any]) -> dict[Any, dict[str, Any]]:
    if not task_ids or not await ready(db):
        return {}
    rows = (await db.execute(select(_T.c.id, _T.c.status, _T.c.progress, _T.c.blocker, _T.c.source_msg_id, _T.c.confidence, _T.c.updated_at)
                             .where(_T.c.id.in_(task_ids)))).all()
    return {r[0]: {"status": r[1], "progress": r[2], "blocker": r[3], "source_msg_id": str(r[4]) if r[4] else None, "confidence": r[5],
                   "updated_at": r[6].isoformat() if r[6] else None} for r in rows}
